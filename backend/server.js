import "dotenv/config";
import express from "express";
import http from "node:http";
import cors from "cors";
import helmet from "helmet";
import {Server} from "socket.io";
import {connectDB} from "./config/db.js";
import {setIO} from "./utils/notify.js";
import authRoutes from "./routes/auth.js";
import doctorRoutes from "./routes/doctors.js";
import appointmentRoutes from "./routes/appointments.js";
import prescriptionRoutes from "./routes/prescriptions.js";
const required=["JWT_SECRET"];
for(const k of required)if(!process.env[k]){console.error(`${k} is required. Copy .env.example to .env and configure it.`);process.exit(1);}
await connectDB();
const app=express(),server=http.createServer(app);
const origins=(process.env.CLIENT_URL||"http://localhost:5173").split(",").map(x=>x.trim());
const io=new Server(server,{cors:{origin:origins,methods:["GET","POST","PATCH","DELETE"]}});
setIO(io);
io.on("connection",socket=>{socket.on("join",({userId,role}={})=>{if(userId)socket.join(String(userId));if(role)socket.join(`role:${role}`);});});
app.use(helmet({crossOriginResourcePolicy:{policy:"cross-origin"}}));
app.use(cors({origin:(origin,cb)=>!origin||origins.includes(origin)?cb(null,true):cb(new Error("CORS origin not allowed"))}));
app.use(express.json({limit:"1mb"}));
app.get("/",(req,res)=>res.json({ok:true,service:"Healthcare Intelligence API"}));
app.get("/health",(req,res)=>res.json({ok:true,database:process.env.MONGODB_URI?"configured":"not-configured"}));
app.use("/api/auth",authRoutes);app.use("/api/doctors",doctorRoutes);app.use("/api/appointments",appointmentRoutes);app.use("/api/prescriptions",prescriptionRoutes);
app.use((err,req,res,next)=>{console.error(err.message);res.status(500).json({message:"Internal server error"});});
const port=Number(process.env.PORT)||5000;server.listen(port,"0.0.0.0",()=>console.log(`Healthcare API listening on ${port}`));
